def get_category_slug(name: str) -> Optional[str]:
    """Возвращает category_slug по названию товара или None."""
    if not name or not name.strip():
        return None
    name_lower = name.lower().strip()
    # Исключение: стяжка шлифовальная — не категория стяжек
    if "стяжка" in name_lower and ("шлифовальн" in name_lower or "эксцентриковая шлиф" in name_lower):
        pass
    else:
        for slug, keywords in _CATEGORY_RULES:
            for kw in keywords:
                if kw == "лоток":
                    if "лоток" in name_lower and "молоток" not in name_lower:
                        return slug
                    continue
                if kw in name_lower:
                    return slug
    if "лоток" in name_lower and "молоток" not in name_lower:
        return "vnutrennee-napolnenie"
    return None
